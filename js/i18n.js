let lang = 'ur';

export function setLang(l) {
  lang = STRINGS[l] ? l : 'ur';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ur' ? 'rtl' : 'ltr';
}

export function getLang() { return lang; }

export function t(key, ...args) {
  const v = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (typeof v === 'function') return v(...args);
  if (Array.isArray(v)) return v[Math.floor(Math.random() * v.length)];
  return v;
}

// Class for interface text: Urdu text needs the Nastaliq font.
export function uiClass() { return lang === 'ur' ? 'ur' : ''; }
